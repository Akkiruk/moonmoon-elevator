-- Landing computers: hall calls arrive as rednet events, the hub answers with a landing message per car per floor.
package.path = "/?.lua;/?/init.lua;" .. package.path
local H = require "tests.harness"

ccunit.test("a hall call lights its button and the lantern shows on arrival", function()
  local w = H.world({ start = { A = "P3", B = "6" } })
  w:hall("3", "down")
  w:run(0.1)
  local l = w:landing("B", "3")
  ccunit.eq(l.type, "landing")
  ccunit.eq(l.floor, "3")
  ccunit.eq(l.car, "B")
  ccunit.eq(l.down, true, "down lit")
  ccunit.eq(l.up, false)
  ccunit.eq(w:landing("A", "3").down, true, "both shafts' indicators see the call")
  ccunit.truthy(w:runUntil(function() return w:car("B").moving end, 3))
  w:run(1)
  l = w:landing("B", "3")
  ccunit.eq(l.dir, "down")
  ccunit.eq(l.carFloor ~= nil, true)
  ccunit.eq(l.mode, "normal")
  ccunit.eq(l.outOfOrder, false)
  ccunit.truthy(w:runUntil(function() return w:landing("B", "3").lantern == "down" end, 30), "lantern lit while arriving")
  ccunit.truthy(w:arriveOpen("B", "3", 30))
  l = w:landing("B", "3")
  ccunit.eq(l.lantern, "down")
  ccunit.eq(l.down, false, "answered")
  ccunit.eq(l.carFloor, "3")
  ccunit.eq(l.doors, "open")
  ccunit.eq(w:landing("B", "G").lantern, nil, "only at its own floor")
end, { timeout = 15 })

ccunit.test("calls the hub won't take are ignored", function()
  local w = H.world({ start = { A = "G", B = "6" } })
  w:hall("6", "up")
  w:hall("L1", "down")
  w:hall("nowhere", "up")
  w:hall("3", "sideways")
  w:run(0.2)
  ccunit.eq(w.ctl.hall.up[11], nil)
  ccunit.eq(w.ctl.hall.down[1], nil)
  ccunit.eq(w:car("A").moving, false)
  w.plant.lockdown = true
  w:run(0.1)
  w:hall("L2", "up")
  w:run(0.1)
  ccunit.eq(w.ctl.hall.up[2], nil, "lockdown")
  w.plant.lockdown = false
  w.plant.fire = true
  w:run(0.1)
  w:hall("4", "up")
  w:run(0.1)
  ccunit.eq(w.ctl.hall.up[9], nil, "fire")
end, { timeout = 10 })

ccunit.test("one car only: car B absent from the config", function()
  local w = H.world({ start = { A = "P1" }, config = function(cfg) cfg.cars.B = nil end })
  ccunit.eq(w.ctl.order, { "A" })
  w:hall("5", "down")
  w:run(0.2)
  ccunit.eq(w.ctl.hall.down[10], "A")
  ccunit.truthy(w:arriveOpen("A", "5", 60))
  ccunit.eq(w.out.cars.B, nil)
  ccunit.eq(w.ctl:landingState("A", 10).car, "A")
end, { timeout = 10 })

ccunit.test("the shipped config runs car A alone", function()
  local cfg = require "config"
  local E = require "elevator"
  local ctl = E.new(cfg)
  ccunit.eq(ctl.order, { "A" })
  local out = ctl:step(0, { cars = { A = { y = 108, yTime = 0, door = { open = false, ok = true, t = 0 } } } })
  ccunit.eq(out.cars.A.release, false)
  ccunit.eq(out.cars.B, nil)
end, { timeout = 5 })

ccunit.test("a floor with no contact configured skips the cross-check", function()
  local w = H.world({ start = { A = "G", B = "6" } })
  w:p("A").noContact[8] = true -- floor 3 has none; it would never light
  w:p("A").deadContacts[8] = true
  w:call("A", "5")
  ccunit.truthy(w:arriveOpen("A", "5", 40))
  ccunit.eq(w:mode("A"), "normal")
end, { timeout = 10 })
