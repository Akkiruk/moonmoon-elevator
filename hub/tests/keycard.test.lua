-- Keycard floors: L1 and L2 only after a swipe in the cab (10 s window).
package.path = "/?.lua;/?/init.lua;" .. package.path
local H = require "tests.harness"

ccunit.test("L1 without a card does nothing", function()
  local w = H.world({ start = { A = "G", B = "6" } })
  w:call("A", "L1")
  w:run(1)
  ccunit.eq(w:state("A").message, "Swipe keycard first")
  w:run(4)
  ccunit.eq(w:car("A").calls[1], nil)
  ccunit.eq(w:car("A").moving, false)
  ccunit.eq(w.ctl:panelState("A").lit.L1, nil)
end, { timeout = 10 })

ccunit.test("swipe, then press: the car goes", function()
  local w = H.world({ start = { A = "G", B = "6" } })
  w:keycard("A")
  w:run(0.1)
  ccunit.eq(w.ctl:panelState("A").keycard_window, true)
  w:run(3)
  w:call("A", "L2")
  w:run(0.1)
  ccunit.eq(w.ctl:panelState("A").lit.L2, true)
  ccunit.truthy(w:arriveOpen("A", "L2", 60))
end, { timeout = 15 })

ccunit.test("the window closes after 10 s; the card is per car", function()
  local w = H.world({ start = { A = "G", B = "6" } })
  w:keycard("A")
  w:run(11)
  ccunit.eq(w.ctl:panelState("A").keycard_window, false)
  w:call("A", "L1")
  w:run(0.1)
  ccunit.eq(w:car("A").calls[1], nil, "too late")
  w:keycard("B")
  w:call("A", "L1")
  w:run(0.1)
  ccunit.eq(w:car("A").calls[1], nil, "B's swipe does not open A")
end, { timeout = 10 })

ccunit.test("hall calls at L1/L2 need no card", function()
  local w = H.world({ start = { A = "G", B = "6" } })
  w:hall("L2", "up")
  ccunit.truthy(w:arriveOpen("A", "L2", 60))
end, { timeout = 15 })
